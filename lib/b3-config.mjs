import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

// Minimal per-instance B3 runtime configuration (Block 12). The full config
// generator with RCON password, MySQL DSN and b3hide/auth wiring is Block 16.
// Format checked against eBc-B3 b3/conf/b3.xml: <configuration><settings name>
// <set name>. Storage: SQLite (b3/storage/sqlite.py imports @b3/sql/sqlite/b3.sql
// on first connect), so the lifecycle does not depend on the Block 14 database.
const samePath = (a, b) => process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b;
const fail = code => { throw Object.assign(new Error(code), { code }); };
const escapeXml = value => String(value).replace(/[<>&'"]/g, char => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[char]);

export function b3Paths(instance) {
  const directory = path.join(instance.homePath, 'b3');
  return { directory, config: path.join(directory, 'b3.xml'), database: path.join(directory, 'b3.db'), logFile: path.join(directory, 'b3.log'), stdout: path.join(directory, 'b3-stdout.log'), stderr: path.join(directory, 'b3-stderr.log') };
}

// CoD4x writes g_log relative to <fs_homepath>/main (no fs_game in the managed profile).
export function gameLogPath(instance, gLog) {
  if (typeof gLog !== 'string' || !/^(?:logs\/)?[a-zA-Z0-9_-]+\.log$/.test(gLog)) fail('B3_GAME_LOG_NOT_CONFIGURED');
  return path.join(instance.homePath, 'main', ...gLog.split('/'));
}

export function renderB3Config({ instance, paths, gameLog, databaseDsn = null }) {
  const set = (name, value) => `    <set name="${name}">${escapeXml(value)}</set>`;
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    databaseDsn ? '<!-- Generated by COD4X CONTROL. Do not edit; contains the B3 database password (mode 0600). -->'
      : '<!-- Generated by COD4X CONTROL (Block 12 minimal runtime config). Do not edit; contains no credentials. -->',
    '<configuration>',
    '  <settings name="b3">', set('bot_name', 'b3'), set('bot_prefix', '^0(^2b3^0)^7:'), set('time_format', '%I:%M%p %Z %m/%d/%y'), set('time_zone', 'UTC'),
    set('log_level', '9'), set('logfile', paths.logFile), set('parser', 'cod4x'), set('database', databaseDsn || `sqlite://${paths.database.replace(/\\/g, '/')}`), '  </settings>',
    // rcon_password stays empty until the vault transfer of Block 16.
    // public_ip must stay 127.0.0.1 even for publicly bound instances: B3's must-have
    // publist plugin reports the server to bigbrotherbot.net over plain HTTP otherwise
    // (b3/plugins/publist/__init__.py onStartup). rcon_ip is a separate setting.
    '  <settings name="server">', set('rcon_password', ''), set('port', instance.port), set('public_ip', '127.0.0.1'), set('rcon_ip', '127.0.0.1'),
    set('delay', '0.33'), set('lines_per_second', '50'), set('punkbuster', 'off'), set('game_log', gameLog), '  </settings>',
    // No autodoc section: B3 then skips documentationBuilder (b3/parser.py updateDocumentation).
    '  <settings name="update">', set('channel', 'skip'), '  </settings>',
    '  <settings name="plugins">', set('external_dir', '@b3/extplugins'), '  </settings>',
    // admin is mandatory for B3 (parser: "missing mandatory plugin").
    '  <plugins>', '    <plugin name="admin" config="@b3/conf/plugin_admin.ini"/>', '  </plugins>',
    '</configuration>', '',
  ].join('\n');
}

export async function safeDirectory(directory, create) {
  try {
    const stats = await fs.lstat(directory);
    if (!stats.isDirectory() || stats.isSymbolicLink() || !samePath(await fs.realpath(directory), path.resolve(directory))) fail('B3_DIRECTORY_INVALID');
  } catch (error) {
    if (error.code !== 'ENOENT' || !create) throw error.code?.startsWith('B3_') ? error : Object.assign(new Error('B3_DIRECTORY_INVALID'), { code: 'B3_DIRECTORY_INVALID' });
    await fs.mkdir(directory, { recursive: true, mode: 0o700 });
    return safeDirectory(directory, false);
  }
}

// Writes b3.xml atomically (0600) and makes sure the game log exists, without
// truncating it, so B3 can start independently of the CoD4x server.
export async function prepareB3Runtime(instance, gLog, { databaseDsn = null } = {}) {
  const paths = b3Paths(instance);
  const gameLog = gameLogPath(instance, gLog);
  await safeDirectory(paths.directory, true);
  await safeDirectory(path.dirname(gameLog), true);
  try {
    const stats = await fs.lstat(gameLog);
    if (!stats.isFile() || stats.isSymbolicLink() || stats.nlink !== 1) fail('B3_GAME_LOG_UNSAFE');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await (await fs.open(gameLog, 'a', 0o644)).close();
  }
  const text = renderB3Config({ instance, paths, gameLog, databaseDsn });
  const temporary = `${paths.config}.tmp-${crypto.randomUUID()}`;
  await fs.writeFile(temporary, text, { flag: 'wx', mode: 0o600 });
  await fs.rename(temporary, paths.config);
  return { ...paths, gameLog, sha256: crypto.createHash('sha256').update(text).digest('hex') };
}
