import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

// Per-instance B3 runtime configuration: minimal runtime (Block 12), MySQL DSN
// (Block 14), RCON password from the vault and the auth plugin for b3hide
// (Block 16, eBc-B3 b3/extplugins/auth.py).
// Format checked against eBc-B3 b3/conf/b3.xml: <configuration><settings name>
// <set name>. Storage: SQLite (b3/storage/sqlite.py imports @b3/sql/sqlite/b3.sql
// on first connect), so the lifecycle does not depend on the Block 14 database.
const samePath = (a, b) => process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b;
const fail = code => { throw Object.assign(new Error(code), { code }); };
const escapeXml = value => String(value).replace(/[<>&'"]/g, char => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[char]);

export function b3Paths(instance) {
  const directory = path.join(instance.homePath, 'b3');
  return { directory, config: path.join(directory, 'b3.xml'), authConfig: path.join(directory, 'plugin_auth.ini'), database: path.join(directory, 'b3.db'), logFile: path.join(directory, 'b3.log'), stdout: path.join(directory, 'b3-stdout.log'), stderr: path.join(directory, 'b3-stderr.log') };
}

// CoD4x writes g_log relative to <fs_homepath>/main (no fs_game in the managed profile).
export function gameLogPath(instance, gLog) {
  if (typeof gLog !== 'string' || !/^(?:logs\/)?[a-zA-Z0-9_-]+\.log$/.test(gLog)) fail('B3_GAME_LOG_NOT_CONFIGURED');
  return path.join(instance.homePath, 'main', ...gLog.split('/'));
}

export function renderB3Config({ instance, paths, gameLog, databaseDsn = null, rconPassword = '', authConfigPath = null }) {
  const set = (name, value) => `    <set name="${name}">${escapeXml(value)}</set>`;
  const secrets = [databaseDsn && 'the B3 database password', rconPassword && 'the RCON password'].filter(Boolean);
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    secrets.length ? `<!-- Generated by COD4X CONTROL. Do not edit; contains ${secrets.join(' and ')} (mode 0600). -->`
      : '<!-- Generated by COD4X CONTROL. Do not edit; contains no credentials. -->',
    '<configuration>',
    '  <settings name="b3">', set('bot_name', 'b3'), set('bot_prefix', '^0(^2b3^0)^7:'), set('time_format', '%I:%M%p %Z %m/%d/%y'), set('time_zone', 'UTC'),
    set('log_level', '9'), set('logfile', paths.logFile), set('parser', 'cod4x'), set('database', databaseDsn || `sqlite://${paths.database.replace(/\\/g, '/')}`), '  </settings>',
    // rcon_password comes from the vault inside the B3 start scope (Block 16); empty without one.
    // public_ip must stay 127.0.0.1 even for publicly bound instances: B3's must-have
    // publist plugin reports the server to bigbrotherbot.net over plain HTTP otherwise
    // (b3/plugins/publist/__init__.py onStartup). rcon_ip is a separate setting.
    '  <settings name="server">', set('rcon_password', rconPassword || ''), set('port', instance.port), set('public_ip', '127.0.0.1'), set('rcon_ip', '127.0.0.1'),
    set('delay', '0.33'), set('lines_per_second', '50'), set('punkbuster', 'off'), set('game_log', gameLog), '  </settings>',
    // No autodoc section: B3 then skips documentationBuilder (b3/parser.py updateDocumentation).
    '  <settings name="update">', set('channel', 'skip'), '  </settings>',
    '  <settings name="plugins">', set('external_dir', '@b3/extplugins'), '  </settings>',
    // admin is mandatory for B3 (parser: "missing mandatory plugin").
    '  <plugins>', '    <plugin name="admin" config="@b3/conf/plugin_admin.ini"/>',
    ...(authConfigPath ? [`    <plugin name="auth" config="${escapeXml(authConfigPath)}"/>`] : []), '  </plugins>',
    '</configuration>', '',
  ].join('\n');
}

// Default texts from eBc-B3 auth.py onLoadConfig. Passwords contain no '%'
// (validB3AuthPassword), so Python 2.7's ConfigParser reads every value verbatim.
const AUTH_MESSAGES = Object.freeze([
  ['auth_message', '^7Please authenticate yourself with ^1!auth <password>'],
  ['auth_done', '^1You have been authenticated!'],
  ['already_done', '^1You have already been authenticated!'],
  ['bad_auth', '^1Wrong password!'],
  ['no_password', '^1Missing password!^7 Usage: !auth <password>'],
]);

export function renderAuthConfig({ passwords = {} } = {}) {
  const levels = Object.keys(passwords).map(Number).sort((a, b) => a - b);
  return [
    '; Generated by COD4X CONTROL. Do not edit' + (levels.length ? '; contains !auth passwords (mode 0600).' : '.'),
    '[commands]', 'auth: 0', '',
    '[messages]', ...AUTH_MESSAGES.map(([key, value]) => `${key}: ${value}`), '',
    ...(levels.length ? ['[passwords]', ...levels.map(level => `${level}: ${passwords[level]}`), ''] : []),
  ].join('\n');
}

async function writePrivate(file, text) {
  const temporary = `${file}.tmp-${crypto.randomUUID()}`;
  await fs.writeFile(temporary, text, { flag: 'wx', mode: 0o600 });
  await fs.rename(temporary, file);
}

export async function safeDirectory(directory, create) {
  try {
    const stats = await fs.lstat(directory);
    if (!stats.isDirectory() || stats.isSymbolicLink() || !samePath(await fs.realpath(directory), path.resolve(directory))) fail('B3_DIRECTORY_INVALID');
  } catch (error) {
    if (error.code !== 'ENOENT' || !create) throw error.code?.startsWith('B3_') ? error : Object.assign(new Error('B3_DIRECTORY_INVALID'), { code: 'B3_DIRECTORY_INVALID' });
    await fs.mkdir(directory, { recursive: true, mode: 0o700 });
    return safeDirectory(directory, false);
  }
}

// Writes b3.xml atomically (0600) and makes sure the game log exists, without
// truncating it, so B3 can start independently of the CoD4x server.
export async function prepareB3Runtime(instance, gLog, { databaseDsn = null, rconPassword = '', auth = null } = {}) {
  const paths = b3Paths(instance);
  const gameLog = gameLogPath(instance, gLog);
  await safeDirectory(paths.directory, true);
  await safeDirectory(path.dirname(gameLog), true);
  try {
    const stats = await fs.lstat(gameLog);
    if (!stats.isFile() || stats.isSymbolicLink() || stats.nlink !== 1) fail('B3_GAME_LOG_UNSAFE');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    await (await fs.open(gameLog, 'a', 0o644)).close();
  }
  const text = renderB3Config({ instance, paths, gameLog, databaseDsn, rconPassword, authConfigPath: auth ? paths.authConfig : null });
  // The returned hashes identify the generated files for the API and logs. They
  // are fingerprints of the non-secret inputs only, never of the file text: an
  // unsalted hash of a file holding a short password would allow guessing that
  // password offline (CodeQL js/insufficient-password-hash). Secrets only enter
  // as "present or not".
  const inputs = { port: instance.port, paths, gameLog, mysql: databaseDsn ? true : false, rcon: rconPassword ? true : false, auth: auth ? true : false };
  const fingerprint = file => crypto.createHash('sha256').update(JSON.stringify({ file, ...inputs })).digest('hex');
  let authSha256 = null;
  if (auth) {
    await writePrivate(paths.authConfig, renderAuthConfig(auth));
    authSha256 = fingerprint('plugin_auth.ini');
  } else await fs.rm(paths.authConfig, { force: true });
  await writePrivate(paths.config, text);
  return { ...paths, gameLog, sha256: fingerprint('b3.xml'), authSha256 };
}
