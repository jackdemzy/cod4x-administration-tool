// Usage: node scripts/generate-b3-plugin-catalog.mjs <path to eBc-B3 checkout>
// Regenerates lib/b3-plugin-catalog.mjs from a checkout at the pinned commit.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { B3_SOURCE, normalizedHash } from '../lib/b3-dependencies.mjs';
import { hashB3Module } from '../lib/b3-plugin-hash.mjs';

const output = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'b3-plugin-catalog.mjs');
const FIXED = ['admin', 'publist', 'auth'];
const PYTHON_MODULES = ['requests', 'feedparser', 'paramiko'];

const stringList = (text, name) => {
  const match = new RegExp(`^\\s*${name}\\s*=\\s*\\[([^\\]]*)\\]`, 'm').exec(text);
  return match ? [...match[1].matchAll(/['"]([^'"]+)['"]/g)].map(item => item[1]) : [];
};

async function listPyFiles(directory) {
  const found = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) { if (entry.name !== '__pycache__') found.push(...await listPyFiles(full)); } else if (entry.name.endsWith('.py')) found.push(full);
  }
  return found;
}

async function configTemplate(root, name) {
  const candidates = [];
  for (const ext of ['ini', 'xml']) candidates.push(`b3/conf/plugin_${name}.${ext}`);
  for (const base of [`plugin_${name}`, name]) for (const ext of ['ini', 'xml']) candidates.push(`b3/extplugins/conf/${base}.${ext}`);
  for (const relative of candidates) {
    const data = await fs.readFile(path.join(root, ...relative.split('/'))).catch(() => null);
    if (data) return { configTemplate: relative, configTemplateSha256: normalizedHash(data) };
  }
  return { configTemplate: null, configTemplateSha256: null };
}

async function describe(root, location, name, kind) {
  const base = path.join(root, 'b3', location, kind === 'package' ? name : `${name}.py`);
  const hashed = await hashB3Module(base);
  if (!hashed.ok) throw new Error(`cannot hash ${location}/${name}: ${hashed.code}`);
  const main = await fs.readFile(kind === 'package' ? path.join(base, '__init__.py') : base, 'latin1');
  const sources = kind === 'package' ? await listPyFiles(base) : [base];
  const imported = new Set();
  for (const file of sources) {
    const text = await fs.readFile(file, 'latin1');
    for (const module of PYTHON_MODULES) if (new RegExp(`^\\s*(?:import|from)\\s+${module}\\b`, 'm').test(text)) imported.add(module);
  }
  return {
    name, location, module: kind, sha256: hashed.sha256,
    ...await configTemplate(root, name),
    requiresConfigFile: !/^\s*requiresConfigFile\s*=\s*False\b/m.test(main),
    requiresPlugins: stringList(main, 'requiresPlugins'),
    requiresParsers: stringList(main, 'requiresParsers'),
    pythonModules: [...imported].sort(),
  };
}

async function scan(root) {
  const entries = [];
  for (const location of ['plugins', 'extplugins']) {
    for (const item of await fs.readdir(path.join(root, 'b3', location), { withFileTypes: true })) {
      if (item.name === '__init__.py' || item.name === 'conf') continue;
      if (item.isFile() && item.name.endsWith('.py')) {
        const name = item.name.slice(0, -3);
        if (!FIXED.includes(name)) entries.push(await describe(root, location, name, 'file'));
      } else if (item.isDirectory() && !FIXED.includes(item.name)) {
        // A directory without __init__.py is not importable as a B3 plugin (extplugins/discordbot).
        if (await fs.stat(path.join(root, 'b3', location, item.name, '__init__.py')).catch(() => null)) entries.push(await describe(root, location, item.name, 'package'));
      }
    }
  }
  return entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

const render = entries => `// GENERATED by scripts/generate-b3-plugin-catalog.mjs from eBc-B3 ${B3_SOURCE.commit}.
// Do not edit by hand: regenerate from a checkout at that commit.
// Block 16b: the shipped B3 plugins, their module hashes and the attributes B3 reads
// from the plugin classes. admin, publist and auth are fixed and never listed here.
import path from 'node:path';

const entry = value => Object.freeze({ ...value, requiresPlugins: Object.freeze(value.requiresPlugins), requiresParsers: Object.freeze(value.requiresParsers), pythonModules: Object.freeze(value.pythonModules) });

export const B3_CATALOG_COMMIT = '${B3_SOURCE.commit}';
export const B3_FIXED_PLUGINS = Object.freeze(${JSON.stringify(FIXED)});

export const B3_PLUGIN_CATALOG = Object.freeze([
${entries.map(item => `  entry(${JSON.stringify(item)}),`).join('\n')}
]);

export const catalogEntry = name => B3_PLUGIN_CATALOG.find(item => item.name === name) || null;

// The CoD4x parser is 'cod4x'; a plugin that lists other parsers only cannot run on it.
export const isAvailable = item => !item.requiresParsers.length || item.requiresParsers.includes('cod4x');

export const modulePath = (b3Path, item) => path.join(b3Path, 'b3', item.location, item.module === 'file' ? \`\${item.name}.py\` : item.name);
`;

async function main() {
  const [b3Path] = process.argv.slice(2);
  if (!b3Path) throw new Error('usage: generate-b3-plugin-catalog.mjs <b3Path>');
  const root = path.resolve(b3Path);
  const { stdout } = await promisify(execFile)('git', ['-C', root, 'rev-parse', 'HEAD']);
  if (stdout.trim() !== B3_SOURCE.commit) throw new Error(`refusing: ${root} is at ${stdout.trim()}, expected ${B3_SOURCE.commit}`);
  const entries = await scan(root);
  await fs.writeFile(output, render(entries));
  console.log(`wrote ${entries.length} entries to ${output}`);
}

main().catch(error => { console.error(error.message); process.exitCode = 1; });
